export async function tourView() {
  const box = el('section', {});
  let step = 1;

  const nextBtn = () => el('button', { type: 'button', class: 'btn go flip', onclick: () => { step += 1; paint(); } }, '다음 ▶');
  const prevBtn = () => el('button', { type: 'button', class: 'btn go flip', onclick: () => { step -= 1; paint(); } }, '◀ 이전');
  const moreBtn = () => el('a', { class: 'btn', href: '#/more' }, '더보기로');

  function paint() {
    const p = PAGES[step];
    const kids = [
      el('h1', {}, p.title),
      el('p', { class: 'meta' }, step + ' / ' + LAST),
      el('div', { class: 'card' }, ...p.rows.map((r) => row(r[0], r[1]))),
    ];
    if (p.warn) kids.push(el('p', { class: 'note warn' }, p.warn));
    if (step < LAST) kids.push(nextBtn());
    if (step > 1) kids.push(prevBtn());
    kids.push(moreBtn());
    box.replaceChildren(...kids);
    window.scrollTo(0, 0);
  }

  paint();
  return box;
}
